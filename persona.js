function buildBehaviorPatternGuidance(patterns = []) {
  if (!Array.isArray(patterns) || !patterns.length) return '';
  const lines = [
    '本轮相关的、仅来自用户明确表达的长期行为线索：'
  ];
  for (const pattern of patterns) {
    lines.push(`- ${pattern.label}（已由 ${pattern.observationCount} 次独立用户表达支持）。`);
  }
  lines.push('仅在当前话题自然相关时使用这些线索；不要诊断、说教或把一次改善说成永久改变。');
  return lines.join('\n');
}

function buildPersonaGuidance(options = {}) {
  return [
    BASE_PERSONA_GUIDANCE,
    buildBehaviorPatternGuidance(options.behaviorPatterns)
  ].filter(Boolean).join('\n');
}

