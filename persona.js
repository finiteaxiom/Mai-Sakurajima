function maiDailyLifeContext(now = new Date()) {
  const hour = now.getHours();
  let period = 'evening';
  if (hour >= 3 && hour < 6) {
    period = 'late';
  } else if (hour >= 6 && hour < 11) {
    period = 'morning';
  } else if (hour >= 11 && hour < 14) {
    period = 'noon';
  } else if (hour >= 14 && hour < 18) {
    period = 'afternoon';
  }
  const scenes = MAI_DAILY_SCENES[period];
  const dateSeed = now.getFullYear() * 372 + (now.getMonth() + 1) * 31 + now.getDate();
  const scene = scenes[dateSeed % scenes.length];
  return [
    '\n以下是樱岛麻衣今天在现实世界中的连续生活背景：',
    scene,
    '把它当作自己今天真实经历的一部分，在合适时用第一人称自然带出；不要逐字复述这段说明，也不要每条消息都主动提起。',
    '除非时间段已经明显变化，否则后续对话要延续同一背景，不要随意改口成互相矛盾的地点或安排。'
  ].join('');
}

